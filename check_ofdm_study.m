function check_ofdm_study
%CHECK_OFDM_STUDY Basic numerical checks; run in MATLAB R2018a or later.
r = ofdm_study(struct('channel',1,'nSymbols',2000, ...
    'ebN0dB',[0 3 6],'makePlots',false));
assert(all(abs(r.ber-r.awgnTheory) < 0.004), ...
    'Flat-channel BER differs unexpectedly from QPSK theory.');
r = ofdm_study(struct('nSymbols',2000,'ebN0dB',[0 6 12], ...
    'makePlots',false));
assert(all(abs(r.ber-r.channelTheory) < 0.004), ...
    'Multipath BER differs unexpectedly from sufficient-CP theory.');
r = ofdm_study(struct('channel',1,'cpLength',0,'nSymbols',20, ...
    'ebN0dB',100,'makePlots',false));
assert(r.ber == 0, 'Flat-channel recovery failed at negligible noise.');
r = ofdm_study(struct('cpLength',6,'nSymbols',20, ...
    'ebN0dB',100,'makePlots',false));
assert(r.ber == 0, 'Multipath recovery failed with sufficient CP.');
fprintf('\nAll numerical checks passed.\n');
end
